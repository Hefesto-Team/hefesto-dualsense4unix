    while IFS= read -r linha; do
        resto=$(printf '%s' "$linha" | sed -E "s/${RUIDO_MEDIDO}//gI")
        if printf '%s' "$resto" | grep -qEi "$FORBIDDEN"; then
            printf '%s\n' "$linha"
        fi
    done
}

